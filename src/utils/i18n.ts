const LANG_MAP: Record<string, LangCode> = {
  tr: "tr", en: "en", ar: "ar", de: "de", ur: "ur",
  "en-US": "en", "en-GB": "en", "ar-SA": "ar", "ar-AE": "ar",
  "de-DE": "de", "de-AT": "de", "de-CH": "de",
  "ur-PK": "ur", "ur-IN": "ur",
};

export function detectLanguage(): LangCode {
  const raw = navigator.language || "tr";
  return LANG_MAP[raw] || LANG_MAP[raw.slice(0, 2)] || "tr";
}

const FALLBACK: Record<string, LangCode> = { tr: "en", en: "tr", ar: "en", de: "en", ur: "en" };
const STORE: Record<LangCode, Record<string, string>> = { tr, en, ar, de, ur };

export function t(key: string, lang: LangCode, vars?: Record<string, string>): string {
  let val = STORE[lang]?.[key] || STORE[FALLBACK[lang]]?.[key] || key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      val = val.replace(`{${k}}`, v);
    }
  }
  return val;
}
